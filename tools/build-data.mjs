// Joins data/sorb-raw.csv with data/geocache.json into data.js. Run tools/geocode.mjs first.
import { readFileSync, writeFileSync } from 'node:fs';
import { readRegistry, geoKey, TOWNS } from './registry.mjs';

const AS_OF = '2026-10-22'; // update on each registry refresh
const cache = JSON.parse(readFileSync('data/geocache.json', 'utf8'));

// Attach each listing's official registry page code. sorb-links.csv is in the same row order as sorb-raw.csv;
// every row is checked against town, level, type and address so no link lands on the wrong pin.
const all = readRegistry();
const raw = readFileSync('data/sorb-raw.csv', 'utf8').trim().split(/\r?\n/).slice(1);
const links = readFileSync('data/sorb-links.csv', 'utf8').trim().split(/\r?\n/).slice(1).map(l => l.split(','));
if (links.length !== all.length) throw new Error(`links ${links.length} vs registry ${all.length}`);
// Registry prefixes say "LOWELL MA 01852" (sometimes cut to "LOWELL M"); our rows say "LOWELL 01852 (NM)"
const squash = s => s.toUpperCase().replace(/\(.*$/, '').replace(/\sMA?\s*$/, '').replace(/\bMA\b/g, '').replace(/[^A-Z0-9]/g, '');
const sameAddr = (a, b) => { const n = Math.min(a.length, b.length); return n >= 6 && a.slice(0, n) === b.slice(0, n); };
all.forEach((r, i) => {
  const [town, level, type, prefix, link] = links[i];
  const addr = squash(raw[i].match(/"([^"]*)"/)[1]);
  if (town !== r.town || +level !== r.level || type !== r.type || !sameAddr(addr, squash(prefix)) || !/^[\w-]{20,}$/.test(link)) {
    throw new Error(`Row ${i + 1} mismatch: ${links[i].join(',')} vs ${raw[i]}`);
  }
  r.link = link;
});
const rows = all.filter(r => !r.dupe);

const locs = new Map();
const unmapped = [];
const perTown = {};
for (const r of rows) {
  perTown[TOWNS[r.town]] = (perTown[TOWNS[r.town]] || 0) + 1;
  const g = r.mappable && cache[geoKey(r)];
  if (!g) { unmapped.push({ town: TOWNS[r.town], level: r.level, type: r.type, link: r.link }); continue; }
  // Same street address listed under two zips (e.g. Billerica vs North Billerica) is one building
  const twin = [...locs.values()].find(l => l.street === r.street && Math.hypot((l.lat - g.lat) * 111, (l.lng - g.lng) * 82) < 0.1);
  const key = twin ? twin.key : geoKey(r);
  if (!locs.has(key)) locs.set(key, { key, street: r.street, city: r.city, zip: r.zip, lat: g.lat, lng: g.lng, ...(g.approx ? { approx: true } : {}), entries: [] });
  locs.get(key).entries.push({ level: r.level, type: r.type, link: r.link });
}

const out = {
  asOf: AS_OF, source: 'https://sorb.chs.state.ma.us/sorbpublic/', towns: Object.values(TOWNS), perTown,
  total: rows.length, locations: [...locs.values()].map(({ key, ...l }) => l), unmapped,
};
writeFileSync('site/lowell/data.js', '// Generated by tools/build-data.mjs. Do not edit by hand.\nwindow.SAFEWALK_DATA = ' + JSON.stringify(out) + ';\n');
const linked = rows.filter(r => r.link).length;
console.log(`listings ${rows.length} | locations ${locs.size} | pinned ${rows.length - unmapped.length} | unmapped ${unmapped.length} | linked ${linked}`, perTown);
