// Builds site/nashua from data/nh-raw.csv (run tools/nh-scrape.mjs first): geocodes new addresses, writes data.js,
// and copies the shared app files from site/lowell so both cities run the same page.
import { readFileSync, writeFileSync, mkdirSync, cpSync } from 'node:fs';
import { geoKey } from './registry.mjs';
import { geocodeMissing } from './geocoder.mjs';
import { REGIONS } from './regions.mjs';

const AS_OF = '2026-10-23'; // update on each registry refresh
const TOWNS = { NASHUA: 'Nashua', HUDSON: 'Hudson', MERRIMACK: 'Merrimack', LITCHFIELD: 'Litchfield', HOLLIS: 'Hollis', AMHERST: 'Amherst' };
const SUFFIX = { STREET: 'ST', AVENUE: 'AVE', ROAD: 'RD', DRIVE: 'DR', LANE: 'LN', SQUARE: 'SQ', TRAIL: 'TRL', CIRCLE: 'CIR', COURT: 'CT' };

// "23 TEMPLE ST 410 NASHUA NH, 03060" -> { street: '23 TEMPLE ST', city: 'NASHUA', zip: '03060' }
function parse(address) {
  const m = address.match(/^(.*) ([A-Z]+) NH, (\d{5})$/);
  if (!m) return null; // out of state
  const words = m[1].split(' ').filter(w => !/^1\/2/.test(w)).map(w => SUFFIX[w] || w);
  // Drop unit numbers after the street name: "410", "E103", "R11", "2ND FL"
  while (words.length > 2 && (/\d/.test(words.at(-1)) || words.at(-1) === 'FL')) words.pop();
  const mappable = /^\d/.test(words[0] || '');
  return { street: mappable ? words.join(' ') : '', city: m[2], zip: m[3], mappable };
}

const lines = readFileSync('data/nh-raw.csv', 'utf8').trim().split(/\r?\n/).slice(1);
const byId = new Map();
let outOfState = 0;
for (const l of lines) {
  const [, town, id, address] = l.match(/^(\w+),(\d+),"([^"]*)"/);
  const a = parse(address);
  if (!a) { outOfState++; continue; }
  const r = { town: TOWNS[a.city] ? a.city : town, id, ...a };
  // A person can show under two towns (one listing homeless, one with a street address): keep the mappable one
  const prev = byId.get(id);
  if (!prev || (!prev.mappable && r.mappable)) byId.set(id, r);
}
const rows = [...byId.values()];

const cache = await geocodeMissing(rows, 'NH');
const locs = new Map();
const unmapped = [];
const perTown = {};
for (const r of rows) {
  const town = TOWNS[r.town];
  perTown[town] = (perTown[town] || 0) + 1;
  const g = r.mappable && cache[geoKey(r)];
  if (!g) { unmapped.push({ town, type: 'LISTED', link: r.id }); continue; }
  const key = geoKey(r);
  if (!locs.has(key)) locs.set(key, { street: r.street, city: r.city, zip: r.zip, lat: g.lat, lng: g.lng, ...(g.approx ? { approx: true } : {}), entries: [] });
  locs.get(key).entries.push({ type: 'LISTED', link: r.id });
}

const region = REGIONS.nashua;
const out = {
  asOf: AS_OF, source: region.registryHome, region, towns: Object.values(TOWNS), perTown,
  total: rows.length, locations: [...locs.values()], unmapped,
};
mkdirSync('site/nashua', { recursive: true });
writeFileSync('site/nashua/data.js', '// Generated by tools/build-nashua.mjs. Do not edit by hand.\nwindow.SAFEWALK_DATA = ' + JSON.stringify(out) + ';\n');

// Same app page and worker as Lowell; only the title, description and install name differ
const page = readFileSync('site/lowell/index.html', 'utf8')
  .replace(/<title>.*<\/title>/, '<title>SafeWalk Nashua</title>')
  .replace(/<meta name="description" content="[^"]*">/, '<meta name="description" content="Halloween walking map of addresses on the New Hampshire State Police public offender registry in Nashua, Hudson, Merrimack, Litchfield, Hollis and Amherst, NH.">');
writeFileSync('site/nashua/index.html', page);
cpSync('site/lowell/sw.js', 'site/nashua/sw.js');
cpSync('site/lowell/icons', 'site/nashua/icons', { recursive: true });
const manifest = JSON.parse(readFileSync('site/lowell/manifest.webmanifest', 'utf8'));
manifest.name = 'SafeWalk Nashua';
manifest.description = 'Halloween walking map of public registry addresses in Nashua, NH and the five towns around it.';
writeFileSync('site/nashua/manifest.webmanifest', JSON.stringify(manifest, null, 2) + '\n');

console.log(`listings ${rows.length} | locations ${locs.size} | pinned ${rows.length - unmapped.length} | unmapped ${unmapped.length} | out of state ${outOfState}`, perTown);
