// Builds site/nh/data.js (statewide New Hampshire) from data/nh-state-raw.csv (`node tools/nh-scrape.mjs --state`, all 10
// counties) plus data/nh-all-raw.csv when present (`--nh-all`, State = NEW HAMPSHIRE with no county), reconciling the two.
// Every listing is placed: its building, else its street, else its town. Writes only data.js; the app files in site/nh are
// maintained separately.
import { readFileSync, writeFileSync, mkdirSync, statSync, existsSync } from 'node:fs';
import { geoKey, parseNsorAddress } from './registry.mjs';
import { geocodeMissing, recheckGeocodes, placeAll } from './geocoder.mjs';
import { REGIONS } from './regions.mjs';

const AS_OF = '2026-10-23'; // update on each registry refresh
const title = s => s.toLowerCase().replace(/\b[a-z]/g, c => c.toUpperCase());
const COUNTIES = ['Belknap', 'Carroll', 'Cheshire', 'Coos', 'Grafton', 'Hillsborough', 'Merrimack', 'Rockingham', 'Strafford', 'Sullivan'];

function splitCsv(line) {
  const out = []; let cur = '', q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') { if (q && line[i + 1] === '"') { cur += '"'; i++; } else q = !q; }
    else if (ch === ',' && !q) { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}
const readCsv = file => existsSync(file) ? readFileSync(file, 'utf8').trim().split(/\r?\n/).slice(1).map(splitCsv) : [];

// County pulls and the one statewide search should list the same people; report any difference and keep the union
const byCounty = readCsv('data/nh-state-raw.csv'), byState = readCsv('data/nh-all-raw.csv');
const idsC = new Set(byCounty.map(f => f[1])), idsS = new Set(byState.map(f => f[1]));
const onlyCounty = [...idsC].filter(i => !idsS.has(i)), onlyState = [...idsS].filter(i => !idsC.has(i));
if (byState.length) console.log(`reconcile: county pulls ${idsC.size} IDs, statewide search ${idsS.size} IDs, only in counties ${onlyCounty.length}, only statewide ${onlyState.length}`);

// One row per person and address. A person listed twice (homeless in one town, a street address in another, or two
// registered addresses) keeps every row: each is a place the registry lists them.
const seen = new Set();
const rows = [];
let outOfState = 0, rawRows = 0;
for (const [county, id, address, city, state, rowCounty] of [...byCounty, ...byState]) {
  rawRows++;
  if (state && state !== 'NH') { outOfState++; continue; }
  const a = parseNsorAddress(address, city, 'NH');
  if (!a) { outOfState++; continue; }
  const key = id + '|' + (a.mappable ? geoKey(a) : city + '|' + a.text);
  if (seen.has(key)) continue;
  seen.add(key);
  // The registry once shows a town in the county column (PIKE); only the ten real counties are kept
  const c = title(county || rowCounty || '');
  rows.push({ town: city, county: COUNTIES.includes(c) ? c : '', id, ...a });
}
if (outOfState) throw new Error(`${outOfState} rows are outside New Hampshire; the state search should not return any`);
const people = new Set(rows.map(r => r.id));

const cache = await geocodeMissing(rows, 'NH');
// Misses and wrong-street Census hits get a second try from OpenStreetMap; see recheckGeocodes in geocoder.mjs
const fix = await recheckGeocodes(rows, cache, 'NH', r => r.town);
console.log('recheck:', JSON.stringify({ ...fix, examples: undefined }));
const { locations, placement, fallbacks } = await placeAll(rows, cache, 'NH', {
  townOf: r => r.town, countyOf: r => r.county, entryOf: r => ({ type: 'LISTED', link: r.id }), stateCenter: REGIONS.nh.center,
});

const perTown = {};
for (const r of rows) perTown[title(r.town)] = (perTown[title(r.town)] || 0) + 1;
const region = REGIONS.nh;
const registries = {
  MA: { name: REGIONS.ma.registryName, whoUrl: REGIONS.ma.whoUrl, terms: REGIONS.ma.terms },
  NH: { name: region.registryName, whoUrl: region.whoUrl, terms: region.terms },
};
const out = {
  asOf: AS_OF, source: region.registryHome, region, registries, towns: Object.keys(perTown).sort(), perTown,
  total: rows.length, people: people.size, placement, locations, unmapped: [],
};
mkdirSync('site/nh', { recursive: true });
writeFileSync('site/nh/data.js', '// Generated by tools/build-nh.mjs. Do not edit by hand.\nwindow.SAFEWALK_DATA = ' + JSON.stringify(out) + ';\n');

// Sanity report (addresses masked, no names exist in the input)
const countyOf = {};
for (const r of rows) countyOf[r.county] = (countyOf[r.county] || 0) + 1;
console.log(`raw rows ${rawRows} | listings ${rows.length} | people ${people.size} | locations ${locations.length} | placement ${JSON.stringify(placement)}`);
console.log('town lookups that fell back to the county center:', fallbacks.county.length, fallbacks.county, '| to the state center:', fallbacks.state);
console.log('listings per county:', countyOf);
console.log('towns:', out.towns.length, '| Nashua:', perTown.Nashua);
console.log('top locations:', [...locations].sort((a, b) => b.entries.length - a.entries.length).slice(0, 10)
  .map(l => `${l.entries.length} ${l.street ? l.street.replace(/^\d+[A-Z]?(-\d+)?/, '#') : '(town center)'}, ${title(l.city)}${l.place ? ' [' + l.place + ']' : ''}`));
console.log('data.js bytes:', statSync('site/nh/data.js').size);
